//! The input model: a [`Document`] made of typed [`Block`]s.
//!
//! Extractors (HTML, PDF, Markdown, ...) produce this shape. With the `serde`
//! feature it round-trips through JSON using snake_case names, and every
//! optional field may be absent on input.

use alloc::string::String;
use alloc::vec::Vec;

/// The structural role of a [`Block`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum BlockKind {
    /// A section heading; see [`Block::level`].
    Heading,
    /// Ordinary prose.
    #[default]
    Paragraph,
    /// One item of a list; see [`Block::depth`] and [`Block::ordered`].
    ListItem,
    /// Quoted prose; nesting is carried by [`Block::quote`].
    Blockquote,
    /// Preformatted source code; see [`Block::lang`].
    Code,
    /// A table flattened to text.
    Table,
    /// An image or other figure (usually its alt text).
    Figure,
    /// A caption for a figure or table.
    Caption,
    /// A footnote or endnote.
    Footnote,
    /// A horizontal rule / section break.
    Rule,
}

impl BlockKind {
    /// Every kind, in declaration order.
    pub const ALL: [BlockKind; 10] = [
        BlockKind::Heading,
        BlockKind::Paragraph,
        BlockKind::ListItem,
        BlockKind::Blockquote,
        BlockKind::Code,
        BlockKind::Table,
        BlockKind::Figure,
        BlockKind::Caption,
        BlockKind::Footnote,
        BlockKind::Rule,
    ];

    /// The text shown by a marker token standing in for a skipped block of
    /// this kind, e.g. `"[code]"`. Marker text is generated by the engine and
    /// is never author text.
    pub const fn marker_label(self) -> &'static str {
        match self {
            BlockKind::Heading => "[heading]",
            BlockKind::Paragraph => "[paragraph]",
            BlockKind::ListItem => "[list item]",
            BlockKind::Blockquote => "[quote]",
            BlockKind::Code => "[code]",
            BlockKind::Table => "[table]",
            BlockKind::Figure => "[figure]",
            BlockKind::Caption => "[caption]",
            BlockKind::Footnote => "[footnote]",
            BlockKind::Rule => "[rule]",
        }
    }
}

/// One structural unit of a document.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct Block {
    /// What this block is.
    pub kind: BlockKind,
    /// The author's text, verbatim.
    #[cfg_attr(feature = "serde", serde(default))]
    pub text: String,
    /// Heading level, `1..=6`, for headings.
    #[cfg_attr(feature = "serde", serde(default))]
    pub level: Option<u8>,
    /// List nesting depth for list items; `1` is top level.
    #[cfg_attr(feature = "serde", serde(default))]
    pub depth: Option<u8>,
    /// Whether a list item belongs to an ordered list.
    #[cfg_attr(feature = "serde", serde(default))]
    pub ordered: Option<bool>,
    /// Blockquote nesting depth; `0` means not quoted.
    #[cfg_attr(feature = "serde", serde(default))]
    pub quote: u8,
    /// Language tag for code blocks.
    #[cfg_attr(feature = "serde", serde(default))]
    pub lang: Option<String>,
    /// The extractor's hint that this block should not be read word by word.
    #[cfg_attr(feature = "serde", serde(default))]
    pub skip: bool,
}

impl Block {
    /// A block of `kind` with `text` and every other field at its default.
    pub fn new(kind: BlockKind, text: impl Into<String>) -> Block {
        Block {
            kind,
            text: text.into(),
            ..Block::default()
        }
    }

    /// A paragraph block.
    pub fn paragraph(text: impl Into<String>) -> Block {
        Block::new(BlockKind::Paragraph, text)
    }

    /// A heading block at `level` (`1..=6`).
    pub fn heading(level: u8, text: impl Into<String>) -> Block {
        Block {
            level: Some(level),
            ..Block::new(BlockKind::Heading, text)
        }
    }
}

/// Where a document's content came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum Source {
    /// A Readability-style main-content extraction.
    Readability,
    /// `articleBody` from JSON-LD structured data.
    JsonLd,
    /// Only the page's meta description was available.
    MetaDescription,
    /// The abstract declared by scholarly citation metadata
    /// (`citation_abstract`), used because the page body held no article.
    CitationAbstract,
    /// Plain text input.
    PlainText,
    /// Markdown input.
    Markdown,
    /// Text extracted from a PDF.
    Pdf,
    /// Unknown or no content.
    #[default]
    None,
}

/// A readable document: metadata plus an ordered list of blocks.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct Document {
    /// The URL the document was read from; empty if none.
    #[cfg_attr(feature = "serde", serde(default))]
    pub url: String,
    /// The document title; empty if unknown.
    #[cfg_attr(feature = "serde", serde(default))]
    pub title: String,
    /// Author attribution.
    #[cfg_attr(feature = "serde", serde(default))]
    pub byline: Option<String>,
    /// Publication or site name.
    #[cfg_attr(feature = "serde", serde(default))]
    pub site_name: Option<String>,
    /// Content language as a BCP 47 tag.
    #[cfg_attr(feature = "serde", serde(default))]
    pub lang: Option<String>,
    /// A short summary supplied by the source page.
    #[cfg_attr(feature = "serde", serde(default))]
    pub excerpt: Option<String>,
    /// How the content was obtained.
    #[cfg_attr(feature = "serde", serde(default))]
    pub source: Source,
    /// The content is known or suspected to be incomplete.
    #[cfg_attr(feature = "serde", serde(default))]
    pub partial: bool,
    /// The page looked paywalled.
    #[cfg_attr(feature = "serde", serde(default))]
    pub paywall_hint: bool,
    /// Number of words a reader plays by default: the words of the blocks
    /// that [`ReadPolicy::default`](crate::ReadPolicy) reads. Code, tables,
    /// figures, captions, footnotes and rules are not counted.
    #[cfg_attr(feature = "serde", serde(default))]
    pub word_count: usize,
    /// The content, in reading order.
    #[cfg_attr(feature = "serde", serde(default))]
    pub blocks: Vec<Block>,
}

impl Document {
    /// A document holding `blocks`, with `word_count` computed from them (see
    /// [`Document::word_count`]) and all other metadata empty.
    pub fn from_blocks(blocks: Vec<Block>) -> Document {
        let word_count = crate::ReadPolicy::default().word_count(&blocks);
        Document {
            word_count,
            blocks,
            ..Document::default()
        }
    }

    /// A document from plain text: paragraphs are separated by one or more
    /// blank (whitespace-only) lines. Each paragraph's text is kept verbatim
    /// apart from trimming surrounding whitespace, so single line breaks
    /// inside a paragraph are preserved. `source` is [`Source::PlainText`].
    ///
    /// ```
    /// use meatread_core::{Document, BlockKind};
    /// let doc = Document::from_plain_text("First paragraph.\nStill first.\n\nSecond.");
    /// assert_eq!(doc.blocks.len(), 2);
    /// assert_eq!(doc.blocks[0].kind, BlockKind::Paragraph);
    /// assert_eq!(doc.blocks[0].text, "First paragraph.\nStill first.");
    /// assert_eq!(doc.word_count, 5);
    /// ```
    pub fn from_plain_text(text: &str) -> Document {
        let mut blocks = Vec::new();
        let mut current: Option<(usize, usize)> = None;
        let mut offset = 0;
        for line in text.split_inclusive('\n') {
            let start = offset;
            offset += line.len();
            if line.trim().is_empty() {
                if let Some((s, e)) = current.take() {
                    blocks.push(Block::paragraph(text[s..e].trim()));
                }
            } else {
                let end = start + line.len();
                current = Some(match current {
                    Some((s, _)) => (s, end),
                    None => (start, end),
                });
            }
        }
        if let Some((s, e)) = current {
            blocks.push(Block::paragraph(text[s..e].trim()));
        }
        Document {
            source: Source::PlainText,
            ..Document::from_blocks(blocks)
        }
    }
}
